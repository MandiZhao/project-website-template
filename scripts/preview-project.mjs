import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { readContent, renderIndex } from '../template/build-index.mjs';

export const previewMarker = '<!-- Generated by project-website-template --preview. -->';

// Keep preview output isolated from the existing site's CSS, scripts, and fonts.
export function renderPreview(repository, project) {
  const readTemplate = name => readFileSync(join(repository, 'template', name), 'utf8');
  let html = renderIndex(readContent(join(project, 'content.js')), readTemplate('index.html'), project);
  const font = readFileSync(join(repository, 'template/assets/fonts/InterVariable.woff2')).toString('base64');
  const license = readTemplate('assets/fonts/OFL.txt');
  const css = readTemplate('styles.css').replace('url("assets/fonts/InterVariable.woff2")',
    () => `url("data:font/woff2;base64,${font}")`);
  function replaceOnce(before, after) {
    if (!html.includes(before)) throw new Error(`Preview template marker missing: ${before}`);
    html = html.replace(before, () => after);
  }
  replaceOnce('<html lang="en">', `${previewMarker}\n<html lang="en">`);
  replaceOnce('<meta charset="utf-8">', '<meta charset="utf-8">\n  <meta name="robots" content="noindex">');
  replaceOnce('<link rel="stylesheet" href="styles.css">', `<style>\n/* ${license} */\n${css}\n</style>`);
  replaceOnce('<script src="render-content.js" defer></script>', '');
  replaceOnce('<script src="project.js" defer></script>', '');
  const scripts = ['render-content.js', 'project.js'].map(readTemplate).join('\n');
  // content.js remains editable; deferred loading completes before this event.
  replaceOnce('</body>', `<script>\ndocument.addEventListener('DOMContentLoaded', () => {\n${scripts}\n});\n</script>\n</body>`);
  return html;
}
